"""System-assigned component_id for planned observation points (IK-0037).

component_id is written into code as ``@probe(component_id=...)`` and is the
primary key of runtime history (traces / shadow_results are keyed by
``(system_id, component_id)``). An identifier that must not change is assigned
and kept by the system, never regenerated by the LLM (owner's rule,
2026-11-07): the probe planner only decides *which* symbols to observe, keyed
by ``(path, qualified_name)``, and this module assigns the id.

Resolution order for one symbol ``(path, qualified_name)`` of a System:

1. ``in_code``      -- the ``@probe(component_id=...)`` already present on the
   symbol in the most recent indexed snapshot that has one
   (``code_symbols.component_id``). Runtime history is already keyed by it.
2. ``previous_plan`` -- the component_id of the most recent probe point
   planned for the same ``(path, symbol)`` (not yet applied to code).
3. ``derived``      -- :func:`derive_component_id`, deterministic from
   ``(path, qualified_name)``.

Derivation (``derived``)::

    slug   = kebab(qualified_name)  # lower-case, [a-z0-9] runs joined by "-",
                                    # at most 40 chars, "symbol" when empty
    digest = sha256(f"{path}::{qualified_name}").hexdigest()
    id     = f"{slug}-{digest[:8]}"

The slug keeps the id readable; the digest of the full natural key makes it
stable across runs and processes (no randomness, no clock) and keeps two
symbols with the same name in different files (or ``A.run`` / ``a_run``)
apart. If the derived id is nevertheless already taken in the System by a
different symbol, the digest is lengthened (12, 16, ... 64 hex chars) until
it is free, which is still a pure function of the System's recorded ids.
"""

from __future__ import annotations

import hashlib
import re
import sqlite3
from dataclasses import dataclass
from typing import Dict, Iterable, List, Optional, Set, Tuple

SymbolKey = Tuple[str, str]  # (path, qualified_name)

_SLUG_MAX = 40
_DIGEST_LENGTHS = (8, 12, 16, 24, 32, 64)


def _kebab(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", (text or "").lower()).strip("-")
    slug = slug[:_SLUG_MAX].strip("-")
    return slug or "symbol"


def _digest(path: str, qualified_name: str) -> str:
    return hashlib.sha256(f"{path}::{qualified_name}".encode("utf-8")).hexdigest()


def derive_component_id(path: str, qualified_name: str, digest_len: int = 8) -> str:
    """Deterministic, kebab-case component_id for ``(path, qualified_name)``."""
    return f"{_kebab(qualified_name)}-{_digest(path, qualified_name)[:digest_len]}"


@dataclass
class ComponentIdAssignment:
    component_id: str
    source: str  # "in_code" | "previous_plan" | "derived"


def _used_ids(conn: sqlite3.Connection, system_id: int) -> Dict[str, Set[SymbolKey]]:
    """Every component_id the System already uses, with the symbols using it."""
    used: Dict[str, Set[SymbolKey]] = {}
    for row in conn.execute(
        """SELECT DISTINCT component_id, path, qualified_name FROM code_symbols
           WHERE system_id = ? AND component_id IS NOT NULL AND component_id != ''""",
        (system_id,),
    ).fetchall():
        used.setdefault(row["component_id"], set()).add((row["path"], row["qualified_name"]))
    for row in conn.execute(
        """SELECT DISTINCT component_id, path, symbol FROM probe_points
           WHERE system_id = ?""",
        (system_id,),
    ).fetchall():
        used.setdefault(row["component_id"], set()).add((row["path"], row["symbol"]))
    return used


def assign_component_ids(
    conn: sqlite3.Connection,
    system_id: int,
    symbols: Iterable[SymbolKey],
) -> Dict[SymbolKey, ComponentIdAssignment]:
    """Assign a component_id to each ``(path, qualified_name)`` of a System.

    See the module docstring for the order. Two different symbols are never
    given the same derived id within one call.
    """
    keys: List[SymbolKey] = []
    for key in symbols:
        if key not in keys:
            keys.append(key)
    used = _used_ids(conn, system_id)
    result: Dict[SymbolKey, ComponentIdAssignment] = {}
    for path, qualified_name in keys:
        row = conn.execute(
            """SELECT component_id FROM code_symbols
               WHERE system_id = ? AND path = ? AND qualified_name = ?
                 AND component_id IS NOT NULL AND component_id != ''
               ORDER BY snapshot_id DESC, id DESC LIMIT 1""",
            (system_id, path, qualified_name),
        ).fetchone()
        if row is not None:
            result[(path, qualified_name)] = ComponentIdAssignment(row["component_id"], "in_code")
            continue
        row = conn.execute(
            """SELECT component_id FROM probe_points
               WHERE system_id = ? AND path = ? AND symbol = ?
               ORDER BY id DESC LIMIT 1""",
            (system_id, path, qualified_name),
        ).fetchone()
        if row is not None and row["component_id"]:
            result[(path, qualified_name)] = ComponentIdAssignment(
                row["component_id"], "previous_plan"
            )
            continue
        chosen: Optional[str] = None
        for length in _DIGEST_LENGTHS:
            candidate = derive_component_id(path, qualified_name, length)
            owners = used.get(candidate)
            if owners is None or owners <= {(path, qualified_name)}:
                chosen = candidate
                break
        if chosen is None:  # pragma: no cover - a full sha256 collision
            raise RuntimeError(f"no free component_id for {path}:{qualified_name}")
        used.setdefault(chosen, set()).add((path, qualified_name))
        result[(path, qualified_name)] = ComponentIdAssignment(chosen, "derived")
    return result
