"""Static, code-managed settings metadata (Issue #102).

Explanations for every user-facing configuration setting: what it is for,
which features it affects, what breaks when it is missing or invalid, and
how to fix it. This registry is the single source the per-screen assistant
uses to explain settings; the text is authored in code — never generated by
an LLM (Issue #102 acceptance criterion).

The registry is shared with the deterministic diagnostics service
(Issue #101): every env var a diagnostics check lists in `related_env`
must have an entry here, and `related_checks` cross-references the
diagnostics `check_id` vocabulary. Tests enforce that contract.

probe-agent:
  role: Static settings-explanation metadata registry
  capability: system-configuration-help
  element_type: core
  consumers: [control-server, dashboard]
  operation_kind: read
  state_effects: []
  probe_value: Verify every diagnostics-referenced env var has a static, non-LLM explanation with impact and remediation.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import List, Optional

# Requiredness vocabulary (finite set):
#   required     - the feature it belongs to cannot work without it
#   conditional  - required only under an explicitly stated condition
#   optional     - has a safe default
